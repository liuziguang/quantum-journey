# ======================================================================
# 需求
# ======================================================================
# 给定一个复数列 data：
#   1. 求每个元素的模长
#   2. 找出模长最大的元素，以及它的下标
#   3. 求所有模长之和
#   4. 把整个列表按模长从大到小排序
#
# 说明：需求里的「打印」都不写进函数，统一放在 __main__ 里。


# ======================================================================
# 函数
# ======================================================================
def abs_list(data):
    """返回 data 中每个元素的模长列表。

    输入：复数列表
    输出：数值列表
    """
    result = []
    for z in data:
        result.append(abs(z))
    return result


def argmax(items):
    """返回最大值的下标。

    输入：数值列表（比如上面返回的模长列表）
    输出：整数下标

    思路：先假设第 0 个最大，然后逐个比较，谁大就把下标记下来。
    """
    best_pos = 0
    for i in range(len(items)):
        if items[i] > items[best_pos]:
            best_pos = i
    return best_pos


def total(items):
    """返回所有元素的和。

    输入：数值列表
    输出：一个数
    """
    s = 0
    for x in items:
        s += x
    return s


def sort_desc(data):
    """返回按模长从大到小排序后的新列表。

    关键点：用内置的 sorted()，它返回一个【新列表】，
           不会修改传进来的 data。这一点很重要——
           如果直接改掉调用者的数据，会引发很难查的 bug。

    key=abs     表示"按绝对值（也就是模长）来排"
    reverse=True 表示"降序"
    """
    return sorted(data, key=abs, reverse=True)


# ======================================================================
# 主程序：只负责调用和打印
# ======================================================================
if __name__ == "__main__":
    data = [1 + 2j, 3 - 1j, 0 + 1j, 2 + 0j]

    mags = abs_list(data)              # 复数 → 模长
    i = argmax(mags)                   # 模长 → 下标
    s = total(mags)                    # 模长 → 和
    ordered = sort_desc(data)          # 复数 → 复数（降序）

    print("原始数据  :", data)
    print("模长列表  :", mags)
    print("最大模长的元素:", data[i], "，它的下标是:", i)
    print("模长之和  :", s)
    print("按模长降序:", ordered)

    # 验证一下 sort_desc 没有改掉原列表
    print("原始数据仍然是:", data, "  ← 如果没有变，说明写法是对的")
